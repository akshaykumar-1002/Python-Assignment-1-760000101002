# Q38. Display the length of a string, list, tuple and dictionary
text = "Python"
numbers = [10, 20, 30, 40]
values = (1, 2, 3)
student = {"name": "Akshay", "age": 20}

print("Length of string:", len(text))
print("Length of list:", len(numbers))
print("Length of tuple:", len(values))
print("Length of dictionary:", len(student))
