# Q39. Demonstrate type() with string, list, tuple and dictionary variables
text = "Python"
numbers = [1, 2, 3]
values = (1, 2, 3)
student = {"name": "Akshay"}

print("String type:", type(text))
print("List type:", type(numbers))
print("Tuple type:", type(values))
print("Dictionary type:", type(student))
